function renderSvg(art, bg, palette) {
  if (art.length !== VIEW_H / CELL) {
    throw new Error(`art must have ${VIEW_H / CELL} rows, got ${art.length}`);
  }
  const rects = [];
  art.forEach((row, y) => {
    if (row.length !== VIEW_W / CELL) {
      throw new Error(`row ${y} must be ${VIEW_W / CELL} chars, got ${row.length}`);
    }
    let run = null;
    const flush = () => {
      if (run) {
        rects.push(
          `<rect x="${run.x * CELL}" y="${y * CELL}" width="${run.width}" height="${CELL}" fill="${run.color}"/>`,
        );
        run = null;
      }
    };
    for (let x = 0; x < row.length; x++) {
      const color = palette[row[x]] ?? bg;
      if (color === bg) {
        flush();
        continue;
      }
      if (run && run.color === color) {
        run.width += CELL;
        continue;
      }
      flush();
      run = { x, color, width: CELL };
    }
    flush();
  });
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${VIEW_W} ${VIEW_H}" width="${VIEW_W}" height="${VIEW_H}" shape-rendering="crispEdges">`,
    `  <rect x="0" y="0" width="${VIEW_W}" height="${VIEW_H}" fill="${bg}"/>`,
    ...rects.map((r) => `  ${r}`),
    "</svg>",
    "",
  ].join("\n");
}

mkdirSync(OUT_DIR, { recursive: true });

const outputs = VARIANTS.map((v) => {
  const svg = renderSvg(v.art, v.bg, v.palette);
  const file = join(OUT_DIR, `${v.name}.svg`);
  writeFileSync(file, svg, "utf8");
  console.log(`generated ${file} (${svg.length} bytes)`);
  return file;
});

let failed = 0;
for (const file of outputs) {
  if (!existsSync(file)) {
    console.error(`FAIL: missing ${file}`);
    failed++;
    continue;
  }
  const size = statSync(file).size;
  if (size === 0) {
    console.error(`FAIL: empty ${file}`);
    failed++;
    continue;
  }
  const content = readFileSync(file, "utf8");
  const rectRe = /<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"/g;
  let match;
  let count = 0;
  while ((match = rectRe.exec(content)) !== null) {
    const [x, y, w, h] = match.slice(1).map(Number);
    const aligned = x % CELL === 0 && y % CELL === 0 && w % CELL === 0 && h % CELL === 0;
    const inside = x >= 0 && y >= 0 && x + w <= VIEW_W && y + h <= VIEW_H;
    if (!aligned || !inside) {
      console.error(`FAIL: ${file} rect ${match.slice(1).join(",")} outside viewBox or off-grid`);
      failed++;
    }
    count++;
  }
  console.log(`OK   ${file}: ${size} bytes, ${count} rects, all within viewBox (320x180)`);
}

if (outputs.length !== 26) {
  console.error(`FAIL: expected 26 files, got ${outputs.length}`);
  failed++;
}

if (failed > 0) {
  console.error(`validation failed with ${failed} error(s)`);
  process.exit(1);
}
console.log(`${outputs.length}/26 cover assets generated and validated`);

#!/usr/bin/env node
// 读取 src/themes/presets/*.json,生成 src/styles/theme-tokens.generated.css
// 修改预设后运行:npm run gen:themes
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const presetsDir = join(root, 'src', 'themes', 'presets')
const outFile = join(root, 'src', 'styles', 'theme-tokens.generated.css')

const files = readdirSync(presetsDir).filter((f) => f.endsWith('.json'))
const presets = files.map((f) => JSON.parse(readFileSync(join(presetsDir, f), 'utf8')))

let css = `/* AUTO-GENERATED by scripts/gen-theme-css.mjs — 请勿手改 */
/* 修改 src/themes/presets/*.json 后运行 npm run gen:themes */\n`

for (const preset of presets) {
  css += `\n/* ${preset.name} (${preset.id}) */\n`
  css += `:root[data-theme="${preset.id}"] {\n`
  css += `  --wallpaper-light-src: ${preset.wallpaper.light.startsWith('gradient:') ? preset.wallpaper.light.slice(9) : preset.wallpaper.light};\n`
  css += `  --wallpaper-dark-src: ${preset.wallpaper.dark.startsWith('gradient:') ? preset.wallpaper.dark.slice(9) : preset.wallpaper.dark};\n`
  css += `  --mascot-primary: ${preset.mascot.primary};\n`
  css += `  --mascot-secondary: ${preset.mascot.secondary};\n`
  css += `}\n`
  for (const mode of ['light', 'dark']) {
    css += `:root[data-theme="${preset.id}"][data-mode="${mode}"] {\n`
    for (const [key, value] of Object.entries(preset.palette[mode])) {
      css += `  --${key}: ${value};\n`
    }
    css += `}\n`
  }
}

writeFileSync(outFile, css)
console.log(`generated ${outFile} (${presets.length} presets)`)
